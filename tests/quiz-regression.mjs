import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import crypto from 'node:crypto';
const source = fs.readFileSync(new URL('../server.mjs', import.meta.url), 'utf8');
const section = (start, end) => source.slice(source.indexOf(start), source.indexOf(end, source.indexOf(start)));
const now = Date.now();
const attempt = (no, age) => ({ no, startedMs: now - age, order: ['q1'] });
const q = { id: 'test', live: true, questions: [{ id: 'q1', text: 'Q', options: ['A','B'], correct: 0 }], attemptsAllowed: 1, duration: 1, mark: 1, negative: false, showAnswers: false, attempts: { user: [] } };
let saves = 0;
const ctx = { db: { quizzes: [q] }, readBody: async req => req.body, str: x => x, num: x => Number(x) || 0, send: (res, status, data) => ({ status, data }), saveDb: () => saves++, crypto, QUIZ_GRACE_MS: 120000, quizState: () => 'open', Date, console };
vm.createContext(ctx);
vm.runInContext(section('function scoreQuiz(', 'const byOpens') + section('async function quizAction(', '\nfunction scheduleFor('), ctx);
const call = (act, body = {}) => ctx.quizAction({ body: { id: q.id, ...body } }, {}, act, 'POST', {}, 'user', () => true);
q.attempts.user = [attempt(1, 180000)];
assert.equal((await call('submit', { attemptNo: 1, answers: { q1: 0 } })).status, 410);
assert.equal(saves, 0);
assert.equal(q.attempts.user[0].submittedAt, undefined);
assert.equal((await call('start')).status, 400);
assert.equal(ctx.quizCard(q, 'user').canStart, false);
q.attemptsAllowed = 2;
const start = await call('start');
assert.equal(start.data.attemptNo, 2);
assert.equal(q.attempts.user.length, 2);
assert.equal((await call('start')).data.attemptNo, 2);
assert.equal(q.attempts.user.length, 2);
assert.equal((await call('submit', { attemptNo: 1, answers: { q1: 0 } })).status, 410);
assert.equal((await call('submit', { answers: { q1: 0 } })).status, 409);
const result = await call('submit', { attemptNo: 2, answers: { q1: 0 } });
assert.equal(result.status, 200);
assert.equal(result.data.result.score, 1);
assert.equal(q.attempts.user[0].submittedAt, undefined);
assert.ok(q.attempts.user[1].submittedAt);
assert.equal((await call('submit', { attemptNo: 2, answers: {} })).status, 409);
assert.equal((await call('start')).status, 400);
// A delayed automatic submission still works within the existing network grace period.
q.attempts.user = [attempt(1, 90000)];
assert.equal((await call('submit', { attemptNo: 1, answers: { q1: 0 } })).data.result.score, 1);
console.log('Quiz regression checks passed: expiration, limits, resume, attempt binding, duplicates, grace.');
