import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const project = fileURLToPath(new URL("..", import.meta.url));
const root = path.resolve(project, "..");
const dist = path.join(project, "dist");
await fs.mkdir(dist, { recursive: true });
let source = await fs.readFile(path.join(root, "server.mjs"), "utf8");
function replace(from, to) {
  if (!source.includes(from)) throw new Error("Backend changed; review Cloudflare adaptation: " + from.slice(0, 80));
  source = source.replace(from, to);
}
// Generate from the actual backend: fee, exam, order and permission rules stay shared.
const start = source.indexOf('const DATA = path.join(ROOT, "data");');
const staticStart = source.indexOf('// ---------- ফাইল পরিবেশন ----------');
const jobsStart = source.indexOf('syncPauses(); setInterval(syncPauses,');
const listenStart = source.indexOf('server.listen(PORT, HOST,');
if ([start, staticStart, jobsStart, listenStart].some(n => n < 0)) throw new Error("Cannot locate backend sections");
source = source.slice(start, staticStart) + source.slice(jobsStart, listenStart);
replace('const ADMIN_LOCK = process.env.ADMIN_LOCK !== "0";', 'const ADMIN_LOCK = true;');
replace('const PORT = Number(process.env.PORT) || 8090;', 'const PORT = 8090;');
replace('const SMS_BASE = process.env.SMS_BASE || "https://bulksmsbd.net/api";', 'const SMS_BASE = env.SMS_BASE || "https://bulksmsbd.net/api";');
for (const name of ["birthdayTick", "absentTick", "monthlyTick", "feeTick"]) replace(`${name}(); setInterval(${name},`, `setInterval(${name},`);
replace('syncPauses(); setInterval(syncPauses,', 'setInterval(syncPauses,');
replace('async function sendSms(phone, message, logText, filter = "OTP") {', 'async function doSendSms(phone, message, logText, filter = "OTP") {');
// This deployment buffers uploads for atomic SQLite writes. Keep within isolate memory.
replace('function readRaw(req, limit) {', 'function readRaw(req, limit) {\n  limit = Math.min(limit, MAX_UPLOAD);');
replace('function readBody(req, limit = 10 * 1024 * 1024) {', 'function readBody(req, limit = 10 * 1024 * 1024) {\n  limit = Math.min(limit, MAX_UPLOAD);');
replace('function saveUpload(req, file, limit) {', 'function saveUpload(req, file, limit) {\n  limit = Math.min(limit, file.startsWith("/data/ebook-pdfs/") ? MAX_EBOOK_UPLOAD : MAX_UPLOAD);');
replace('video: 300 * 1024 * 1024', 'video: 20 * 1024 * 1024');
source = source.replaceAll('ফাইল অনেক বড় — ৬০ MB-এর মধ্যে দিন', 'ফাইল অনেক বড় — Cloudflare-এ সর্বোচ্চ ২০ MB');
source = source.replaceAll('ভিডিও আপলোড হয়নি — ২ GB-এর মধ্যে দিন', 'ভিডিও আপলোড হয়নি — Cloudflare-এ সর্বোচ্চ ২০ MB; বড় ভিডিওর জন্য YouTube লিংক দিন');

const prefix = `// Generated by scripts/build.mjs. Edit ../server.mjs for business rules.\nimport path from "node:path";\nimport crypto from "node:crypto";\nimport { Buffer } from "node:buffer";\nimport { seedDatabase, makeBatches, DB_VERSION } from "./seed.mjs";\nimport "./examcalc.js";\nimport { DhakaDate as Date } from "./dhaka-date.mjs";\nimport { MAX_UPLOAD, MAX_EBOOK_UPLOAD } from "./sqlite-fs.mjs";\nexport function createApplication(fs, env) {\nconst ROOT = "/";\nconst EC = globalThis.ExamCalc;\nconst jobs = [];\nconst setInterval = (fn) => { jobs.push(fn); return { unref() {} }; };\nconst pending = new Set();\nfunction sendSms(...args) {\n  const task = doSendSms(...args); pending.add(task);\n  task.then(() => pending.delete(task), () => pending.delete(task));\n  return task;\n}\n`;
const suffix = `
const runtimeFile = path.join(DATA, "runtime.json");
const runtime = readJson(runtimeFile, {});
const maps = { loginFails, pinTickets, otps, otpSent, bookHits, qnaHits };
for (const [name, map] of Object.entries(maps)) for (const [k, v] of runtime[name] || []) map.set(k, v);
function persistRuntime() {
  const now = Date.now();
  for (const [k,v] of pinTickets) if (v.exp <= now) pinTickets.delete(k);
  for (const [k,v] of otps) if (v.exp <= now) otps.delete(k);
  for (const [k,v] of loginFails) if (v.until <= now && !v.count) loginFails.delete(k);
  for (const map of [otpSent, bookHits, qnaHits]) for (const [k,v] of map) {
    const recent = v.filter(t => now - t < 3600e3);
    if (recent.length) map.set(k, recent); else map.delete(k);
  }
  const text = JSON.stringify(Object.fromEntries(Object.entries(maps).map(([k,v]) => [k,[...v]])));
  if (text !== lastRuntime) { writeJsonAtomic(runtimeFile, JSON.parse(text)); lastRuntime = text; }
  if (loginsDirty) saveLogins();
}
let lastRuntime = JSON.stringify(runtime);
async function settle() { while (pending.size) await Promise.allSettled([...pending]); persistRuntime(); }
return { api, settle, scheduled: async () => { for (const job of jobs) await job(); await settle(); } };
}\n`;
await fs.writeFile(path.join(dist, "application.mjs"), prefix + source + suffix);
await fs.copyFile(path.join(root, "seed.mjs"), path.join(dist, "seed.mjs"));
await fs.copyFile(path.join(root, "public/js/examcalc.js"), path.join(dist, "examcalc.js"));
for (const name of await fs.readdir(path.join(project, "src"))) if (name.endsWith(".mjs")) await fs.copyFile(path.join(project, "src", name), path.join(dist, name));
// Only public/ goes into static assets; student records and credentials never do.
await fs.cp(path.join(root, "public"), path.join(dist, "public"), { recursive: true });
await fs.writeFile(path.join(dist, "public/_headers"), "/*\n  X-Content-Type-Options: nosniff\n  X-Frame-Options: SAMEORIGIN\n  Referrer-Policy: strict-origin-when-cross-origin\n");
// Match the Cloudflare variant's upload controls to its server-side memory limit.
for (const name of ["admin.js", "admin-exams.js", "admin-learn.js", "admin-qna.js"]) {
  const file = path.join(dist, "public/js", name);
  let js = await fs.readFile(file, "utf8");
  js = js.replaceAll("2 * 1024 * 1024 * 1024", "20 * 1024 * 1024")
    .replaceAll("60 * 1024 * 1024", "20 * 1024 * 1024")
    .replaceAll("২ GB", "২০ MB").replaceAll("2 GB", "20 MB")
    .replaceAll("৬০ MB", "২০ MB")
    .replaceAll('"a-video": 300', '"a-video": 20');
  await fs.writeFile(file, js);
}
console.log("Cloudflare build complete: shared backend, SQLite adapter, public assets. No live data bundled.");
